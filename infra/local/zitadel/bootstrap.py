DOCKER_BIN = shutil.which("docker")

if not DOCKER_BIN:
    raise RuntimeError("docker binary not found in PATH")

logger = structlog.get_logger(__name__)


def wait_for_file(file_path: Path, max_wait_ms: int = 60000) -> None:
    """Block until file_path exists with content or max_wait_ms elapses."""
    start_time = time.time()
    logger.info("Waiting for file to be generated by Zitadel...", file_path=str(file_path))
    while (time.time() - start_time) * 1000 < max_wait_ms:
        if file_path.exists() and file_path.stat().st_size > 10:
            content = file_path.read_text(encoding="utf-8").strip()
            if content.startswith(("{", "ey")):
                logger.info("File found with valid token content!")
                return
        time.sleep(1)
    raise TimeoutError("Timeout waiting for file")


def wait_for_zitadel_ready(
    base_url: str = "http://ucp.localhost:8080", max_wait_sec: int = 60
) -> None:
    """Block until Zitadel HTTP server is accepting connections and /debug/ready returns 200."""
    start = time.time()
    logger.info("Waiting for Zitadel server readiness...", url=f"{base_url}/debug/ready")
    while time.time() - start < max_wait_sec:
        try:
            with httpx.Client(timeout=3.0) as client:
                res = client.get(f"{base_url}/debug/ready")
                if res.status_code == 200:
                    logger.info("Zitadel server is ready and accepting requests!")
                    time.sleep(
                        2.0
                    )  # Brief delay to allow internal gRPC reverse proxy socket initialization
                    return
        except (httpx.RequestError, httpx.HTTPError):
            pass
        time.sleep(1)
    raise TimeoutError("Timeout waiting for Zitadel server to be ready")


def _destroy_existing(script_dir: Path, root_dir: Path) -> None:
    """
    Reset Zitadel to a completely clean state:
      1. Delete any leftover pat.json from the bind-mount directory.
      2. Stop containers and delete volumes — destroys the Postgres database.
    """
    logger.info("🔥 Resetting existing Zitadel state...")

    pat_key_path = script_dir.parent.parent / "cloud" / "zitadel" / "machinekey" / "pat.json"
    if pat_key_path.exists():
        pat_key_path.unlink()
        logger.info("  Cleared: machinekey/pat.json (stale token for wiped database)")

    jwt_profile_path = pat_key_path.parent / "jwt_profile.json"
    if jwt_profile_path.exists():
        jwt_profile_path.unlink()

    subprocess.run(  # noqa: S603 - Docker compose is a trusted local executable
        [
            DOCKER_BIN,
            "compose",
            "--env-file",
            ".env",
            "--env-file",
            "versions.env",
            "-f",
            "docker-compose.yml",
            "-f",
            "docker-compose.identity.yml",
            "down",
            "-v",
            "--remove-orphans",
        ],
        cwd=root_dir,
        check=True,
    )

    logger.info("✅ Full infrastructure state cleared. Ready for fresh bootstrap.")


def _sanitize_env_value(value: str) -> str:
    """Ensure the value is safe to write on a single line in a .env file."""
    if value.startswith("{") and value.endswith("}"):
        return f"'{value}'"

    safe_value = value.replace("\\", "\\\\").replace('"', '\\"')
    safe_value = safe_value.replace("\r", "").replace("\n", "\\n")
    return f'"{safe_value}"'


def _update_env_file(env_path: Path, updates: dict[str, str]) -> None:
    """Write key=value pairs into .env preserving structure."""
    if not env_path.exists():
        return
    lines = env_path.read_text(encoding="utf-8").splitlines(keepends=True)
    updated_keys: set[str] = set()

    for i, line in enumerate(lines):
        for key in updates:
            if line.startswith(f"{key}="):
                safe_value = _sanitize_env_value(updates[key])
                lines[i] = f"{key}={safe_value}\n"
                updated_keys.add(key)
                break

    for key, value in updates.items():
        if key not in updated_keys:
            safe_value = _sanitize_env_value(value)
            if lines and not lines[-1].endswith("\n"):
                lines.append("\n")
            lines.append(f"{key}={safe_value}\n")

    env_path.write_text("".join(lines), encoding="utf-8")


def _provision_zitadel_resources(pat_token: str, root_dir: Path) -> dict[str, str]:
    """
    Provisions all local Zitadel resources directly via its Management and Admin APIs.
    No Pulumi or external IaC CLI required on developer laptops.
    """
    load_dotenv(root_dir / ".env")
    base_url = "http://ucp.localhost:8080"

    company_name = os.getenv("COMPANY_NAME", "FlowWolf")
    company_domain = os.getenv("COMPANY_DOMAIN", "flowwolf.io")
    platform_admin_email = os.getenv("IDENTITY_PLATFORM_ADMIN_EMAIL", f"admin@{company_domain}")
    platform_admin_password = os.getenv(
        "IDENTITY_PLATFORM_ADMIN_PASSWORD",
        os.getenv("IDENTITY_DEFAULT_USER_PASSWORD", "Password1!"),
    )
    ucp_project_name = os.getenv("UCP_PROJECT_NAME", "UCP")
    edi_project_name = os.getenv("EDI_PROJECT_NAME", "EDI")
    idp_project_name = os.getenv("IDP_PROJECT_NAME", "IDP")

    with httpx.Client(base_url=base_url, timeout=15.0) as client:

        def api_post(
            path: str,
            data: dict[str, object],
            org_id: str | None = None,
            retries: int = 10,
        ) -> dict[str, object]:
            headers = {
                "Authorization": f"Bearer {pat_token}",
                "Content-Type": "application/json",
            }
            if org_id:
                headers["x-zitadel-orgid"] = org_id

            for attempt in range(1, retries + 1):
                try:
                    resp = client.post(path, json=data, headers=headers)
                    if resp.status_code in (502, 503):
                        if attempt == retries:
                            resp.raise_for_status()
                        logger.warning(
                            "Zitadel gateway unavailable (warming up internal gRPC), retrying...",
                            path=path,
                            attempt=attempt,
                            status=resp.status_code,
                        )
                        time.sleep(2.0)
                        continue
                    if resp.is_error:
                        logger.exception(
                            "zitadel_api_call_failed",
                            path=path,
                            status=resp.status_code,
                            body=resp.text,
                        )
                        resp.raise_for_status()
                    return resp.json()  # type: ignore[no-any-return]
                except (httpx.RemoteProtocolError, httpx.ConnectError, httpx.ReadTimeout) as err:
                    if attempt == retries:
                        raise
                    logger.warning(
                        "Transient network error calling Zitadel API, retrying...",
                        path=path,
                        attempt=attempt,
                        error=str(err),
                    )
                    time.sleep(2.0)
            raise RuntimeError(f"Failed to post to {path} after retries")

        logger.info("1. Creating Machine Service Account (iam-manager-sa)...")
        sa_resp = api_post(
            "/management/v1/users/machine",
            {
                "userName": "iam-manager-sa",
                "name": "IAM Manager Service Account",
                "accessTokenType": "ACCESS_TOKEN_TYPE_BEARER",
            },
        )
        sa_id = str(sa_resp["userId"])

        logger.info("2. Granting IAM_OWNER instance role to Service Account...")
        api_post("/admin/v1/members", {"userId": sa_id, "roles": ["IAM_OWNER"]})

        logger.info("3. Generating Machine RSA Key for IAM Manager...")
        key_resp = api_post(
            f"/management/v1/users/{sa_id}/keys",
            {"type": "KEY_TYPE_JSON", "expirationDate": "2030-01-01T00:00:00Z"},
        )
        jwt_profile_json = base64.b64decode(str(key_resp["keyDetails"])).decode("utf-8")

        logger.info("4. Creating Platform Organization...", name=company_name)
        org_resp = api_post("/v2/organizations", {"name": company_name})
        org_id = str(
            org_resp.get("organizationId")
            or (
                org_resp.get("details", {}) if isinstance(org_resp.get("details"), dict) else {}
            ).get("id")  # type: ignore[union-attr]
            or org_resp.get("id")
        )

        logger.info("5. Assigning Service Account as Organization Owner...")
        api_post(
            "/management/v1/orgs/me/members",
            {"userId": sa_id, "roles": ["ORG_OWNER"]},
            org_id=org_id,
        )

        logger.info("6. Creating Platform Admin user...", email=platform_admin_email)
        admin_resp = api_post(
            "/v2/users/human",
            {
                "organizationId": org_id,
                "username": platform_admin_email,
                "profile": {
                    "givenName": "Platform",
                    "familyName": "Admin",
                    "displayName": f"{company_name} Platform Admin",
                },
                "email": {
                    "email": platform_admin_email,
                    "isVerified": True,
                },
                "password": {
                    "password": platform_admin_password,
                    "changeRequired": False,
                },
            },
            org_id=org_id,
        )
        admin_id = str(
            admin_resp.get("userId")
            or (
                admin_resp.get("details", {}) if isinstance(admin_resp.get("details"), dict) else {}
            ).get("id")  # type: ignore[union-attr]
            or admin_resp.get("id")
        )

        logger.info("7. Creating UCP Project...", name=ucp_project_name)
        ucp_resp = api_post(
            "/management/v1/projects",
            {
                "name": ucp_project_name,
                "projectRoleAssertion": True,
                "projectRoleCheck": True,
            },
            org_id=org_id,
        )
        ucp_proj_id = str(
            ucp_resp.get("id")
            or (
                ucp_resp.get("details", {}) if isinstance(ucp_resp.get("details"), dict) else {}
            ).get("id")  # type: ignore[union-attr]
        )

        logger.info("8. Configuring UCP Project Roles...")
        for role_key, display_name, group in [
            ("PlatformAdmin", "Platform Administrator", "Platform"),
            ("TenantAdmin", "Tenant Administrator", "Tenant"),
            ("TenantUser", "Standard Tenant User", "Tenant"),
        ]:
            api_post(
                f"/management/v1/projects/{ucp_proj_id}/roles",
                {"roleKey": role_key, "displayName": display_name, "group": group},
                org_id=org_id,
            )

        logger.info("9. Granting PlatformAdmin role to Platform Admin user...")
        api_post(
            f"/management/v1/users/{admin_id}/grants",
            {"projectId": ucp_proj_id, "roleKeys": ["PlatformAdmin"]},
            org_id=org_id,
        )

        logger.info("10. Creating OIDC Web Dashboard Application...")
        dashboard_url = "http://localhost:5173"
        oidc_resp = api_post(
            f"/management/v1/projects/{ucp_proj_id}/apps/oidc",
            {
                "name": "UCP Web Dashboard",
                "redirectUris": [f"{dashboard_url}/callback"],
                "postLogoutRedirectUris": [dashboard_url],
                "responseTypes": ["OIDC_RESPONSE_TYPE_CODE"],
                "grantTypes": ["OIDC_GRANT_TYPE_AUTHORIZATION_CODE"],
                "appType": "OIDC_APP_TYPE_USER_AGENT",
                "authMethodType": "OIDC_AUTH_METHOD_TYPE_NONE",
                "accessTokenType": "OIDC_TOKEN_TYPE_JWT",
                "accessTokenRoleAssertion": True,
                "devMode": True,
            },
            org_id=org_id,
        )
        ucp_web_client_id = str(oidc_resp.get("clientId"))

        logger.info("11. Creating UCP API Application...")
        ucp_api_resp = api_post(
            f"/management/v1/projects/{ucp_proj_id}/apps/api",
            {"name": "UCP API", "authMethodType": "API_AUTH_METHOD_TYPE_PRIVATE_KEY_JWT"},
            org_id=org_id,
        )
        ucp_api_client_id = str(ucp_api_resp.get("clientId"))

        logger.info("12. Creating EDI Project...", name=edi_project_name)
        edi_resp = api_post(
            "/management/v1/projects",
            {
                "name": edi_project_name,
                "projectRoleAssertion": True,
                "projectRoleCheck": False,
            },
            org_id=org_id,
        )
        edi_proj_id = str(
            edi_resp.get("id")
            or (
                edi_resp.get("details", {}) if isinstance(edi_resp.get("details"), dict) else {}
            ).get("id")  # type: ignore[union-attr]
        )

        logger.info("13. Creating EDI API Application...")
        edi_api_resp = api_post(
            f"/management/v1/projects/{edi_proj_id}/apps/api",
            {"name": "EDI API", "authMethodType": "API_AUTH_METHOD_TYPE_PRIVATE_KEY_JWT"},
            org_id=org_id,
        )
        edi_api_client_id = str(edi_api_resp.get("clientId"))

        logger.info("14. Creating IDP Project...", name=idp_project_name)
        idp_resp = api_post(
            "/management/v1/projects",
            {
                "name": idp_project_name,
                "projectRoleAssertion": True,
                "projectRoleCheck": False,
            },
            org_id=org_id,
        )
        idp_proj_id = str(
            idp_resp.get("id")
            or (
                idp_resp.get("details", {}) if isinstance(idp_resp.get("details"), dict) else {}
            ).get("id")  # type: ignore[union-attr]
        )

    return {
        "IDENTITY_PLATFORM_ORG_ID": org_id,
        "IDENTITY_UCP_PROJECT_ID": ucp_proj_id,
        "VITE_IDENTITY_UCP_PROJECT_ID": ucp_proj_id,
        "IDENTITY_EDI_PROJECT_ID": edi_proj_id,
        "IDENTITY_IDP_PROJECT_ID": idp_proj_id,
        "IDENTITY_UCP_WEB_CLIENT_ID": ucp_web_client_id,
        "VITE_IDENTITY_UCP_WEB_CLIENT_ID": ucp_web_client_id,
        "IDENTITY_UCP_API_CLIENT_ID": ucp_api_client_id,
        "IDENTITY_EDI_API_CLIENT_ID": edi_api_client_id,
        "IDENTITY_MACHINE_KEY": jwt_profile_json,
        "IDENTITY_PLATFORM_ADMIN_ID": admin_id,
        "VITE_UCP_API_URL": "http://localhost:3000",
        "VITE_IDENTITY_API_URL": "http://ucp.localhost:8080",
    }


def _run_full_bootstrap(script_dir: Path, root_dir: Path, pat_key_path: Path) -> None:
    """
    Full bootstrap flow:
      1. Start Zitadel (fresh database generates a new ephemeral PAT)
      2. Wait for the ephemeral PAT
      3. Provision Zitadel resources via direct REST API (Zero Pulumi dependency)
      4. Sync outputs directly into .env
      5. Delete the ephemeral PAT
      6. Print developer credentials summary
    """
    logger.info("🚀 Starting Zitadel container...")
    subprocess.run(  # noqa: S603 - Docker compose is a trusted local executable
        [
            DOCKER_BIN,
            "compose",
            "--env-file",
            ".env",
            "--env-file",
            "versions.env",
            "-f",
            "docker-compose.identity.yml",
            "up",
            "-d",
        ],
        cwd=root_dir,
        check=True,
    )

    try:
        wait_for_file(pat_key_path, max_wait_ms=90000)
        raw_text = pat_key_path.read_text(encoding="utf-8").strip()
        if raw_text.startswith("{"):
            try:
                pat_data = json.loads(raw_text)
                pat_token = str(pat_data.get("token", raw_text))
            except json.JSONDecodeError:
                pat_token = raw_text
        else:
            pat_token = raw_text

        logger.info("Zitadel container is healthy and ephemeral PAT is ready.")
        wait_for_zitadel_ready()

        env_updates = _provision_zitadel_resources(pat_token, root_dir)

        env_path = root_dir / ".env"
        _update_env_file(env_path, env_updates)
        logger.info("✅ Successfully synchronized Zitadel outputs to .env")

        logger.info("✅ Zitadel bootstrap completed successfully!")

        subprocess.run(  # noqa: S603 - sys.executable is a trusted path
            [sys.executable, str(root_dir / "infra" / "scripts" / "print_credentials.py")],
            cwd=root_dir,
            check=False,
        )
    finally:
        logger.info("Cleaning up local ephemeral credentials...")
        pat_key_path.unlink(missing_ok=True)
        jwt_profile_path = pat_key_path.parent / "jwt_profile.json"
        jwt_profile_path.unlink(missing_ok=True)


def main() -> None:
    script_dir = Path(__file__).parent.resolve()
    root_dir = script_dir.parent.parent.parent
    pat_key_path = script_dir.parent.parent / "cloud" / "zitadel" / "machinekey" / "pat.json"

    _destroy_existing(script_dir, root_dir)
    _run_full_bootstrap(script_dir, root_dir, pat_key_path)


if __name__ == "__main__":
    try:
        main()
    except TimeoutError:
        logger.exception("Bootstrap timed out waiting for Zitadel")
        sys.exit(1)
    except RuntimeError:
        logger.exception("Bootstrap configuration error")
        sys.exit(1)
    except subprocess.CalledProcessError:
        sys.exit(1)
    except KeyboardInterrupt:
        logger.warning("Bootstrap cancelled by user.")
        sys.exit(0)
